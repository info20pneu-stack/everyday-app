/** Text for an API error code, or `fallback` for anything unknown. */
export function lbErrorText(code: unknown, lang: Lang, fallback: string): string {
  const msgs = STRINGS[lang] ?? en;
  return typeof code === 'string' && code in msgs ? msgs[code as LbErrorCode] : fallback;
}
